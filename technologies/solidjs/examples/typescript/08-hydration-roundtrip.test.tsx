/**
 * Module 08 — hydration round-trip with the real compiler and both builds.
 *
 * Server half: a child `node` process (server build of @solidjs/web) compiles
 * support/hydration-app.jsx with `generate: "ssr", hydratable: true`, renders it and
 * prints the HTML. Client half (this jsdom test): loads the same fixture compiled with
 * `generate: "dom", hydratable: true` and calls `hydrate()` on the server HTML.
 */
import { describe, it, expect, afterEach } from "vitest";
import { execFileSync } from "node:child_process";
import { createComponent, hydrate } from "@solidjs/web";
import { flush, type Component } from "solid-js";
import { captureDiagnostics } from "./support/diagnostics.ts";

type AppProps = { start: number; label: string };

function serverRender(props: AppProps): { html: string; script: string } {
  return JSON.parse(
    execFileSync(process.execPath, ["examples/typescript/support/hydration-server.mjs", JSON.stringify(props)], {
      cwd: process.cwd(),
      encoding: "utf8",
    }),
  ) as { html: string; script: string };
}

async function loadClientApp(): Promise<Component<AppProps>> {
  const path = ["./.generated", "hydration-app.dom.mjs"].join("/"); // generated by the server half
  return ((await import(/* @vite-ignore */ path)) as { App: Component<AppProps> }).App;
}

/** Install the hydration bootstrap (`_$HY`) the way the inline script would. Idempotent. */
function bootstrap(script: string): void {
  (0, eval)(script.replace(/^<script>/, "").replace(/<\/script>[\s\S]*$/, ""));
}

function mount(html: string): HTMLElement {
  const root = document.createElement("div");
  root.innerHTML = html;
  document.body.append(root);
  return root;
}

const disposers: Array<() => void> = [];
afterEach(() => {
  disposers.splice(0).forEach((d) => d());
  document.body.innerHTML = "";
});

describe("08 · hydration round-trip", () => {
  it("server HTML carries hydration keys and markers; hydrate() adopts the same nodes and makes them live", async () => {
    const { html, script } = serverRender({ start: 1, label: "server" });
    expect(html).toBe("<main _hk=0><button>count <!--$-->1<!--/--></button><p>server</p></main>");
    expect(script).toContain("_$HY"); // the bootstrap that queues early events until hydration

    const root = mount(html);
    bootstrap(script);
    const button = root.querySelector("button")!;
    const App = await loadClientApp();
    disposers.push(hydrate(() => createComponent(App, { start: 1, label: "server" }), root));

    expect(root.querySelector("button")).toBe(button); // claimed, not re-created
    button.click();
    flush();
    expect(button.textContent).toBe("count 2"); // delegated handler attached by hydration
  });

  it("negative: a data mismatch is not repaired; the server's text stays until the binding next changes", async () => {
    const { html, script } = serverRender({ start: 1, label: "server" });
    bootstrap(script);
    const root = mount(html);
    const App = await loadClientApp();
    const { codes } = captureDiagnostics(() => {
      disposers.push(hydrate(() => createComponent(App, { start: 5, label: "client" }), root));
      flush();
    });
    expect(root.textContent).toBe("count 1server"); // client state says 5 / "client": silently stale
    root.querySelector("button")!.click();
    flush();
    expect(root.querySelector("button")!.textContent).toBe("count 6"); // jumps when it next updates
    expect(codes).toEqual([]); // nothing reported in rc.19: test your hydration inputs
  });

  it("negative: structurally foreign HTML is not claimed and nothing renders", async () => {
    bootstrap(serverRender({ start: 1, label: "x" }).script);
    const root = mount("<section>other</section>");
    const App = await loadClientApp();
    disposers.push(hydrate(() => createComponent(App, { start: 1, label: "x" }), root));
    flush();
    expect(root.innerHTML).toBe("<section>other</section>");
  });
});

describe("08 · streaming wire format (hydratable SSR)", () => {
  it("the shell carries a placeholder + fallback and a serialized pending promise; a later chunk swaps in the content", () => {
    const chunks = JSON.parse(
      execFileSync(process.execPath, ["examples/typescript/support/stream-server.mjs"], { cwd: process.cwd(), encoding: "utf8" }),
    ) as string[];
    expect(chunks.length).toBeGreaterThanOrEqual(2);
    const [shell, ...rest] = chunks;
    const later = rest.join("");
    expect(shell).toContain("<h1>shell</h1>"); // shell flushed without waiting
    expect(shell).toMatch(/<template id="pl-\d+"><\/template><i _hk=\d+>wait<\/i><!--pl-\d+-->/); // placeholder + fallback
    expect(shell).toContain('_$HY.r["0"]'); // the async memo's value, as a pending seroval promise record
    expect(later).toMatch(/<template id="\d+"><b _hk=\d+>42<\/b><\/template>/); // resolved fragment
    expect(later).toContain("{n:42}"); // the memo's data, resolving the promise for hydration
    expect(later).toContain("$df("); // the swap function that replaces the fallback
  });
});
